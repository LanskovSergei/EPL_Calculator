// Типы данных калькулятора ГСМ (Шаг 1.1)

export type ТипТС = 'легковой' | 'грузовой';
export type ВидТоплива = 'бензин' | 'дизель';
export type ВидСообщения = 'городское' | 'пригородное' | 'междугородное' | 'международное';

/** Один водитель и его отмеченные рабочие дни (ISO-даты YYYY-MM-DD). */
export interface Водитель {
  фио: string;
  дни: Set<string>;
}

/** Строка заправки с чека. */
export interface Заправка {
  дата: string; // YYYY-MM-DD
  время: string; // HH:mm
  объём: number | ''; // литры
  адрес?: string; // адрес АЗС из чека — для маршрута (Шаг 2.1)
}

/** Полный набор исходных данных формы. */
export interface ВходныеДанные {
  марка: string;
  модель: string;
  типТС: ТипТС;
  видТоплива: ВидТоплива;
  объёмБака: number | '';
  среднийРасход: number | '';
  старше10лет: boolean;
  прицепГруз: boolean;
  спецтехника: boolean;
  периодС: string;
  периодПо: string;
  видСообщения: ВидСообщения;
  срокРейсаДней: number | '';
  одометрНаНачало: number | '';
  остатокНаНачало: number | '';
  водители: Водитель[];
  заправки: Заправка[];
  адресСтоянки?: string; // точка отправления/возврата — для маршрута (Шаг 2.1)
}

/** Результат по одному путевому листу. */
export interface ПутевойЛист {
  номер: number;
  выпуск: string;
  возвращение: string;
  водитель: string;
  общееВремя: number; // часы
  одометрВыдача: number;
  одометрЗакрытие: number;
  пробег: number;
  остатокВыдача: number;
  остатокЗакрытие: number;
  расходНорма: number;
  расходФакт: number;
  видСообщения: ВидСообщения;
  маршрут?: string[]; // текстовый список адресов (Шаг 2.1), если заданы адреса
}

export interface ПримененныйКоэффициент {
  name: string;
  value: number;
}

export interface СводкаРасхода {
  effective: number;
  base: number;
  applied: ПримененныйКоэффициент[];
  note: string;
}

export interface РезультатРасчёта {
  листы: ПутевойЛист[];
  предупреждения: string[];
  расход: СводкаРасхода | null;
}

/** Смена (заготовка путевого листа) до расчёта показателей. */
export interface Смена {
  start: Date;
  days: number;
  driver: string;
}
