import type { ВходныеДанные, Водитель } from './types';
import { toISODate, isWeekend, parseISODate, addDays } from './calc';

export function пустойВодитель(): Водитель {
  return { фио: '', дни: new Set<string>() };
}

export function начальныеДанные(): ВходныеДанные {
  return {
    марка: '',
    модель: '',
    типТС: 'легковой',
    видТоплива: 'бензин',
    объёмБака: '',
    среднийРасход: '',
    старше10лет: false,
    прицепГруз: false,
    спецтехника: false,
    периодС: '',
    периодПо: '',
    видСообщения: 'городское',
    срокРейсаДней: 1,
    одометрНаНачало: '',
    остатокНаНачало: '',
    водители: [пустойВодитель()],
    заправки: [{ дата: '', время: '', объём: '' }],
  };
}

/** Демо-данные из ТЗ: 1 ТС, 2 водителя, июнь, 12 заправок. */
export function демоДанные(): ВходныеДанные {
  const периодС = '2026-06-01';
  const периодПо = '2026-06-30';

  const d1 = new Set<string>();
  const d2 = new Set<string>();
  let cur = parseISODate(периодС);
  const end = parseISODate(периодПо);
  while (cur <= end) {
    if (!isWeekend(cur)) {
      const iso = toISODate(cur);
      if (cur.getDate() <= 15) d1.add(iso);
      else d2.add(iso);
    }
    cur = addDays(cur, 1);
  }

  const refuelDays = [2, 5, 8, 11, 15, 17, 19, 22, 24, 26, 29, 30];

  return {
    марка: 'ГАЗ',
    модель: '3302',
    типТС: 'грузовой',
    видТоплива: 'бензин',
    объёмБака: 64,
    среднийРасход: '',
    старше10лет: false,
    прицепГруз: false,
    спецтехника: false,
    периодС,
    периодПо,
    видСообщения: 'городское',
    срокРейсаДней: 1,
    одометрНаНачало: 52000,
    остатокНаНачало: 20,
    водители: [
      { фио: 'Иванов И.И.', дни: d1 },
      { фио: 'Петров П.П.', дни: d2 },
    ],
    заправки: refuelDays.map((day) => ({
      дата: `2026-06-${String(day).padStart(2, '0')}`,
      время: '09:30',
      объём: 40,
    })),
  };
}
