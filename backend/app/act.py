"""
Сборка сводного «Акта на списание ГСМ» (Шаг 2.3) из результата расчёта
калькулятора — основание для передачи в 1С (см. app/integration_1c.py).
"""
from __future__ import annotations

from .schemas import (
    АктСписанияГСМ,
    ЗапросСинхронизации1С,
    РезультатРасчёта,
    СтрокаАкта,
)


def build_act(req: ЗапросСинхронизации1С, result: РезультатРасчёта) -> АктСписанияГСМ:
    строки = [
        СтрокаАкта(
            номерПЛ=л.номер,
            дата=л.выпуск,
            водитель=л.водитель,
            пробег=л.пробег,
            расходФакт=л.расходФакт,
            расходНорма=л.расходНорма,
        )
        for л in result.листы
    ]

    итого_пробег = round(sum(л.пробег for л in result.листы), 1)
    итого_факт = round(sum(л.расходФакт for л in result.листы), 2)
    итого_норма = round(sum(л.расходНорма for л in result.листы), 2)

    return АктСписанияГСМ(
        организация=req.организация,
        марка=req.расчёт.марка,
        модель=req.расчёт.модель,
        госномер=req.тс.госномер,
        периодС=req.расчёт.периодС,
        периодПо=req.расчёт.периодПо,
        строки=строки,
        итогоПробегКм=итого_пробег,
        итогоРасходФактЛ=итого_факт,
        итогоРасходНормаЛ=итого_норма,
        итогоЭкономияЛ=round(итого_норма - итого_факт, 2),
    )
